def _con_glifo(t):
    ex = dict(t[6]) if len(t) > 6 else {}
    if "g" not in ex:
        n = t[1].lower() + " "
        for k, g in _GLIFOS:
            if k in n:
                ex["g"] = g
                break
    return t[:6] + (ex,) if ex else t


CURADOS = [_con_glifo(t) for t in CURADOS]
